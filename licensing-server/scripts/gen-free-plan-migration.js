'use strict';
// Generates prisma/migrations/20261120120000_free_plan_partner_deals/migration.sql (plain SQL for MariaDB 10.x /
// MySQL 8, applied with the mysql client like the others):
//  1. the PartnerDeal table (Free plan partner offers, src/routes/partnerDeals.js);
//  2. the Free plan row (key free, tier free, amount 0) for every tenant that has none;
//  3. the Free plan copy of the trial_ending / trial_ended / locks_tomorrow built-in emails, only in the rows the
//     admin has not edited (builtIn and isDefault still true).
// Every statement can run twice: CREATE TABLE IF NOT EXISTS, INSERT ... WHERE NOT EXISTS, and UPDATEs that set
// the same values again.
//   node scripts/gen-free-plan-migration.js            print the SQL
//   node scripts/gen-free-plan-migration.js --write    write the migration file
// test/migrations.test.js checks the committed file equals this output.
const fs = require('node:fs');
const path = require('node:path');
const { freePlanCopyRows } = require('../src/email/defaults');
const { TIER_LIMITS, FREE_PLAN_FEATURES } = require('../src/plans/service');

const NAME = '20261120120000_free_plan_partner_deals';
const DIR = path.join(__dirname, '..', 'prisma', 'migrations', NAME);

function sqlString(s) {
  const v = String(s);
  if (v.includes('\\')) throw new Error('Backslashes are not allowed in seeded copy (NO_BACKSLASH_ESCAPES safety).');
  return `'${v.replace(/'/g, "''")}'`;
}

function build() {
  const parts = [];
  parts.push(`-- Free plan and partner deals.
-- Additive only: one new table (PartnerDeal), one new Plan row per tenant (key free, tier free, amount 0, never
-- sold: the checkout refuses it) and the Free plan copy of three built-in trial emails, written only into the
-- template rows the admin has not edited (isDefault = 1). No existing column is added, changed or dropped, no
-- row is deleted. Every statement can run twice (CREATE TABLE IF NOT EXISTS, INSERT ... WHERE NOT EXISTS, UPDATEs
-- that set the same values again). The previous build keeps running on this schema: it never reads PartnerDeal,
-- and GET /v1/plans/public hides the Free plan unless the caller asks include=free, so app 1.0.26 never sees it.
-- Rollback = redeploy the previous build (the extra Plan row and table are then simply unused).
-- Generated by scripts/gen-free-plan-migration.js; test/migrations.test.js checks the two stay identical.`);

  parts.push(`-- 1. Partner offers shown to Free users (GET /v1/partner-deals). Seeded empty: the owner adds deals in the admin.
CREATE TABLE IF NOT EXISTS \`PartnerDeal\` (
    \`id\` VARCHAR(191) NOT NULL,
    \`tenantId\` VARCHAR(191) NOT NULL,
    \`title\` VARCHAR(120) NOT NULL,
    \`vendor\` VARCHAR(80) NOT NULL,
    \`description\` VARCHAR(300) NULL,
    \`url\` VARCHAR(500) NOT NULL,
    \`code\` VARCHAR(60) NULL,
    \`badge\` VARCHAR(40) NULL,
    \`logoUrl\` VARCHAR(500) NULL,
    \`active\` BOOLEAN NOT NULL DEFAULT true,
    \`startsAt\` DATETIME(3) NULL,
    \`endsAt\` DATETIME(3) NULL,
    \`sortOrder\` INTEGER NOT NULL DEFAULT 0,
    \`clicks\` INTEGER NOT NULL DEFAULT 0,
    \`lastClickAt\` DATETIME(3) NULL,
    \`createdAt\` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    \`updatedAt\` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX \`PartnerDeal_tenantId_active_sortOrder_idx\`(\`tenantId\`, \`active\`, \`sortOrder\`),
    PRIMARY KEY (\`id\`),
    CONSTRAINT \`PartnerDeal_tenantId_fkey\` FOREIGN KEY (\`tenantId\`) REFERENCES \`Tenant\`(\`id\`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;`);

  const features = JSON.stringify(FREE_PLAN_FEATURES);
  const limits = JSON.stringify(TIER_LIMITS.free);
  parts.push(`-- 2. The Free plan for every tenant that has no plan with key free (src/plans/service.js ensureFreePlan does the
--    same for new tenants). sortOrder -100: it comes first on the pricing page.
INSERT INTO \`Plan\` (\`id\`, \`tenantId\`, \`key\`, \`name\`, \`tier\`, \`amount\`, \`currency\`, \`interval\`, \`months\`, \`recurring\`, \`active\`,
                    \`description\`, \`highlight\`, \`features\`, \`limits\`, \`sortOrder\`, \`createdAt\`, \`updatedAt\`)
SELECT CONCAT('freeplan', SUBSTRING(SHA2(t.\`id\`, 256), 1, 17)), t.\`id\`, 'free', 'Free', 'free', 0, 'USD', 'month', 1, FALSE, TRUE,
       NULL, FALSE,
       ${sqlString(features)},
       ${sqlString(limits)},
       -100, CURRENT_TIMESTAMP(3), CURRENT_TIMESTAMP(3)
FROM \`Tenant\` t
WHERE NOT EXISTS (SELECT 1 FROM \`Plan\` p WHERE p.\`tenantId\` = t.\`id\` AND p.\`key\` = 'free');`);

  const updates = freePlanCopyRows().map((r) => `UPDATE \`EmailTemplate\`
SET \`name\` = ${sqlString(r.name)},
    \`subject\` = ${sqlString(r.subject)},
    \`html\` = ${sqlString(r.html)},
    \`text\` = ${sqlString(r.text)},
    \`updatedAt\` = CURRENT_TIMESTAMP(3)
WHERE \`key\` = ${sqlString(r.key)} AND \`lang\` = ${sqlString(r.lang)} AND \`builtIn\` = TRUE AND \`isDefault\` = TRUE;`);
  parts.push(`-- 3. Trials now end on the Free plan, nothing locks: the built-in trial emails say so (src/email/defaults.js). Only
--    rows still holding the built-in copy (isDefault = 1) change; a template the admin edited is left alone.
${updates.join('\n\n')}`);
  return parts.join('\n\n') + '\n';
}

if (require.main === module) {
  const sql = build();
  if (process.argv.includes('--write')) {
    fs.mkdirSync(DIR, { recursive: true });
    fs.writeFileSync(path.join(DIR, 'migration.sql'), sql);
    console.log(`Wrote ${path.relative(process.cwd(), path.join(DIR, 'migration.sql'))}`);
  } else {
    process.stdout.write(sql);
  }
}

module.exports = { build, DIR, NAME };
