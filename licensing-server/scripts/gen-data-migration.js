'use strict';
// Generates prisma/migrations/20261107120100_backfill_customers_and_seed/migration.sql:
//  1. Payment.paidAt for settled payments made before the column existed (= createdAt);
//  2. one Customer per distinct owner email the existing installs registered with (source app, not
//     verified by us), keyed exactly like src/customers/emailAddress.js (lowercase; Gmail and
//     Googlemail dots and +tag folded);
//  3. links installs to those customers, and licences / payments to the customers of their installs;
//  4. a first status event (lead, dated when the install was first seen) for each backfilled customer;
//  5. the built-in email templates (src/email/defaults.js) for every tenant.
// Everything is guarded (IS NULL / NOT EXISTS), so a re-run inserts nothing twice.
//   node scripts/gen-data-migration.js            print the SQL
//   node scripts/gen-data-migration.js --write    write the migration file
// test/migrations.test.js checks the committed file equals this output.
const fs = require('node:fs');
const path = require('node:path');
const { defaultRows } = require('../src/email/defaults');

const DIR = path.join(__dirname, '..', 'prisma', 'migrations', '20261107120100_backfill_customers_and_seed');

function sqlString(s) {
  const v = String(s);
  if (v.includes('\\')) throw new Error('Backslashes are not allowed in seeded copy (NO_BACKSLASH_ESCAPES safety).');
  return `'${v.replace(/'/g, "''")}'`;
}

// The emailKey of LOWER(TRIM(col)), as in emailKeyOf().
function emailKeySql(col) {
  const e = `LOWER(TRIM(${col}))`;
  return `CASE WHEN SUBSTRING_INDEX(${e}, '@', -1) IN ('gmail.com', 'googlemail.com')
      THEN CONCAT(REPLACE(SUBSTRING_INDEX(SUBSTRING_INDEX(${e}, '@', 1), '+', 1), '.', ''), '@gmail.com')
      ELSE ${e} END`;
}

function build() {
  const parts = [];
  parts.push(`-- Backfill for the customers / trials / email release, and the default email templates.
-- Generated by scripts/gen-data-migration.js. Every statement only fills empty values or inserts what
-- is missing, so it is safe on the live database and changes no existing value.`);

  parts.push(`-- 1. When settled payments were paid (the column is new; creation time is the best value we have).
UPDATE \`Payment\` SET \`paidAt\` = \`createdAt\` WHERE \`status\` IN ('paid', 'refunded') AND \`paidAt\` IS NULL;`);

  parts.push(`-- 2. One customer per distinct owner email the installs registered with (source app, unverified).
INSERT INTO \`Customer\` (\`id\`, \`tenantId\`, \`email\`, \`emailKey\`, \`source\`, \`status\`, \`statusAuto\`, \`firstSeenAt\`, \`lastSeenAt\`, \`createdAt\`, \`updatedAt\`)
SELECT CONCAT('cm', SUBSTRING(SHA2(CONCAT(x.\`tenantId\`, '|', x.\`emailKey\`), 256), 1, 23)), x.\`tenantId\`, MIN(x.\`email\`), x.\`emailKey\`,
       'app', 'lead', 'lead', MIN(x.\`createdAt\`), MAX(x.\`lastSeenAt\`), CURRENT_TIMESTAMP(3), CURRENT_TIMESTAMP(3)
FROM (
  SELECT i.\`tenantId\`, i.\`createdAt\`, i.\`lastSeenAt\`, LOWER(TRIM(i.\`account\`)) AS \`email\`,
    ${emailKeySql('i.`account`')} AS \`emailKey\`
  FROM \`Install\` i
  WHERE i.\`account\` IS NOT NULL AND CHAR_LENGTH(TRIM(i.\`account\`)) BETWEEN 6 AND 254
    AND LOWER(TRIM(i.\`account\`)) REGEXP '^[a-z0-9!#$%&''*+/=?^_\`{|}~-]+([.][a-z0-9!#$%&''*+/=?^_\`{|}~-]+)*@[a-z0-9-]+([.][a-z0-9-]+)+$'
) x
WHERE NOT EXISTS (SELECT 1 FROM \`Customer\` c WHERE c.\`tenantId\` = x.\`tenantId\` AND c.\`emailKey\` = x.\`emailKey\`)
GROUP BY x.\`tenantId\`, x.\`emailKey\`;`);

  parts.push(`-- 3. Link installs to their customer, and licences / payments to the customer of their install.
UPDATE \`Install\` i
JOIN \`Customer\` c ON c.\`tenantId\` = i.\`tenantId\` AND c.\`emailKey\` = (${emailKeySql('i.`account`')})
SET i.\`customerId\` = c.\`id\`
WHERE i.\`customerId\` IS NULL AND i.\`account\` IS NOT NULL;

UPDATE \`License\` l JOIN \`Install\` i ON i.\`id\` = l.\`installId\`
SET l.\`customerId\` = i.\`customerId\`
WHERE l.\`customerId\` IS NULL AND i.\`customerId\` IS NOT NULL;

UPDATE \`Payment\` p JOIN \`Install\` i ON i.\`id\` = p.\`installId\`
SET p.\`customerId\` = i.\`customerId\`
WHERE p.\`customerId\` IS NULL AND i.\`customerId\` IS NOT NULL;`);

  parts.push(`-- 4. Status history starts as "lead" from the day the install was first seen; the first cron run
-- then records any later status (trial, paid ...) from licences, payments and trials.
INSERT INTO \`CustomerEvent\` (\`id\`, \`tenantId\`, \`customerId\`, \`type\`, \`at\`, \`data\`, \`createdAt\`)
SELECT CONCAT('ev', SUBSTRING(SHA2(CONCAT(c.\`id\`, '|status'), 256), 1, 23)), c.\`tenantId\`, c.\`id\`, 'status', c.\`firstSeenAt\`,
       JSON_OBJECT('from', NULL, 'to', 'lead'), CURRENT_TIMESTAMP(3)
FROM \`Customer\` c
WHERE c.\`source\` = 'app' AND NOT EXISTS (SELECT 1 FROM \`CustomerEvent\` e WHERE e.\`customerId\` = c.\`id\` AND e.\`type\` = 'status');

INSERT INTO \`CustomerEvent\` (\`id\`, \`tenantId\`, \`customerId\`, \`type\`, \`at\`, \`data\`, \`createdAt\`)
SELECT CONCAT('ev', SUBSTRING(SHA2(CONCAT(c.\`id\`, '|created'), 256), 1, 23)), c.\`tenantId\`, c.\`id\`, 'created', c.\`firstSeenAt\`,
       JSON_OBJECT('source', 'app', 'backfill', TRUE), CURRENT_TIMESTAMP(3)
FROM \`Customer\` c
WHERE c.\`source\` = 'app' AND NOT EXISTS (SELECT 1 FROM \`CustomerEvent\` e WHERE e.\`customerId\` = c.\`id\` AND e.\`type\` = 'created');`);

  const seeds = defaultRows().map((r) => `INSERT INTO \`EmailTemplate\` (\`id\`, \`tenantId\`, \`key\`, \`lang\`, \`name\`, \`category\`, \`subject\`, \`html\`, \`text\`, \`builtIn\`, \`isDefault\`, \`createdAt\`, \`updatedAt\`)
SELECT CONCAT('tp', SUBSTRING(SHA2(CONCAT(t.\`id\`, '|${r.key}|${r.lang}'), 256), 1, 23)), t.\`id\`, ${sqlString(r.key)}, ${sqlString(r.lang)}, ${sqlString(r.name)}, ${sqlString(r.category)},
       ${sqlString(r.subject)},
       ${sqlString(r.html)},
       ${sqlString(r.text)},
       TRUE, TRUE, CURRENT_TIMESTAMP(3), CURRENT_TIMESTAMP(3)
FROM \`Tenant\` t
WHERE NOT EXISTS (SELECT 1 FROM \`EmailTemplate\` e WHERE e.\`tenantId\` = t.\`id\` AND e.\`key\` = ${sqlString(r.key)} AND e.\`lang\` = ${sqlString(r.lang)});`);
  parts.push(`-- 5. Built-in email templates (src/email/defaults.js) for every tenant.\n${seeds.join('\n\n')}`);
  return parts.join('\n\n') + '\n';
}

if (require.main === module) {
  const sql = build();
  if (process.argv.includes('--write')) {
    fs.mkdirSync(DIR, { recursive: true });
    fs.writeFileSync(path.join(DIR, 'migration.sql'), sql);
    console.log(`Wrote ${path.relative(process.cwd(), path.join(DIR, 'migration.sql'))}`);
  } else {
    process.stdout.write(sql);
  }
}

module.exports = { build, DIR };
