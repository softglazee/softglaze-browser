const nameCache = new Map();

export function countryName(code, lang = 'en') {
  const key = `${lang}:${code}`;
  if (!nameCache.has(key)) {
    let name = code;
    try { name = new Intl.DisplayNames([lang, 'en'], { type: 'region' }).of(code) || code; } catch { /* old runtime: show the code */ }
    nameCache.set(key, name);
  }
  return nameCache.get(key);
}

// [code, name] pairs for a provider's country picker, sorted by name. A vendor API list (from its
// account lookup) wins; then the catalog's documented `geoSync.countries`; otherwise every country.
export function countryOptions(provider, lang = 'en', apiCountries = []) {
  if (Array.isArray(apiCountries) && apiCountries.length) {
    return apiCountries.map((c) => [String(c.key).toUpperCase(), c.label || countryName(String(c.key).toUpperCase(), lang)]);
  }
  const documented = provider && provider.geoSync && Array.isArray(provider.geoSync.countries) ? provider.geoSync.countries : null;
  const codes = documented || ALL_COUNTRY_CODES;
  return codes.map((code) => [code, countryName(code, lang)]).sort((a, b) => a[1].localeCompare(b[1], lang));
}
